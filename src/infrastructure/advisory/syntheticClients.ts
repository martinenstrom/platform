/** A weekly index series ending at `valuedAt`, 100 at the start, drift and noise seeded per client. */
function performanceSeries(
  seed: number,
  valuedAt: string,
  weeks: number,
  drift: number,
  benchmarkDrift: number,
): readonly PerformancePoint[] {
  const random = new SeededRandom(seed)
  const points: PerformancePoint[] = []
  let portfolio = 100
  let benchmark = 100
  for (let i = weeks; i >= 0; i -= 1) {
    const shock = (random.next() - 0.5) * 2.4
    portfolio = portfolio * (1 + (drift + shock * 1.1) / 100)
    benchmark = benchmark * (1 + (benchmarkDrift + shock) / 100)
    points.push({
      date: addDays(valuedAt, -7 * i),
      portfolio: Math.round(portfolio * 100) / 100,
      benchmark: Math.round(benchmark * 100) / 100,
    })
  }
  const first = points[0]!
  return points.map((p) => ({
    date: p.date,
    portfolio: Math.round((p.portfolio / first.portfolio) * 10000) / 100,
    benchmark: Math.round((p.benchmark / first.benchmark) * 10000) / 100,
  }))
}

function ytdOf(series: readonly PerformancePoint[], today: string): number {
  const year = today.slice(0, 4)
  const start = series.find((p) => p.date >= `${year}-01-01`) ?? series[0]!
  const last = series[series.length - 1]!
  return Math.round(((last.portfolio / start.portfolio) * 100 - 100) * 10) / 10
}

